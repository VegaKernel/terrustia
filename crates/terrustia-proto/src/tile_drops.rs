#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_blocks_drop_themselves() {
        // Anchored against TileID and ItemID from the same build: Gold is tile 8 / item 13, and
        // Silver is tile 9 / item 14, which is the opposite of what the names suggest.
        assert_eq!(tile_drop(0), Some(2), "dirt");
        assert_eq!(tile_drop(1), Some(3), "stone");
        assert_eq!(tile_drop(2), Some(2), "grass drops dirt");
        assert_eq!(tile_drop(6), Some(11), "iron ore");
        assert_eq!(tile_drop(7), Some(12), "copper ore");
        assert_eq!(tile_drop(8), Some(13), "gold ore");
        assert_eq!(tile_drop(9), Some(14), "silver ore");
        assert_eq!(tile_drop(30), Some(9), "wood");
    }

    #[test]
    fn styled_objects_have_no_constant_drop() {
        // Chests and dressers choose their drop from a frame style, so they must not be guessed.
        assert_eq!(tile_drop(21), None, "chest");
        assert_eq!(tile_drop(88), None, "dresser");
    }

    #[test]
    fn unknown_tiles_are_not_invented() {
        assert_eq!(tile_drop(u16::MAX), None);
    }
}
